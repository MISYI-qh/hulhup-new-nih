// DEKS v2: pemeriksa asal foto dan audio buatan Hulhup. Tanpa AI, tanpa layanan luar, tanpa biaya.
//
// Prinsip: Deks hanya MENANDAI bila berkas membawa BUKTI KERAS bahwa ia dibuat/diedit AI. Ciri statistik isi (derau, spektrum,
// keheningan, bandwidth) sudah diukur di korpus uji dan terbukti tidak bisa memisahkan karya AI dari karya asli tanpa salah tuduh,
// jadi tidak pernah dipakai untuk menuduh (lihat DEKS.md). Menuduh orang memakai foto/suara AI padahal asli lebih merusak daripada
// melewatkan satu karya AI yang sudah dihapus jejaknya.
//
// Lapisan foto : c2pa, iptc-xmp, keterangan teks (EXIF/PNG/komentar), parameter generator, data tersembunyi piksel PNG, watermark Stable Diffusion, jejak kamera.
// Lapisan audio: c2pa, iptc-xmp, tag/penulis berkas (ID3, MP4, RIFF, Ogg/Opus/FLAC, WebM).
import { parseImage, cameraEvidence } from './imgmeta.js';
import { parseAudio } from './audmeta.js';
import { decodePixels, stealthInfo, sdWatermark } from './pixels.js';
import { IMG_MAKERS, AUD_MAKERS, VID_MAKERS, AI_CLAIMS, PARAM_PATTERNS, firstHit, sourceTypes, kindOfSource, clean } from './text.js';

export const DEKS_VERSION = '2.0';

const EDIT_CLAIMS = [/\b(edited|enhanced|retouched|modified|altered) (with|by|using) (an? )?(ai|generative)/, /\bgenerative (fill|expand|edit|remove)\b/, /\bmagic editor\b/, /\bcompositewithtrainedalgorithmicmedia\b/];
const C2PA_EXTRA_IMG = [/\bopenai\b/, /\bchatgpt\b/, /\bgpt-4o\b/, /\bgenerated by (openai|google ai|gemini)\b/, /\bfirefly\b/];
const SOFT_KEYS = new Set(['ImageDescription', 'UserComment', 'XPComment', 'XPTitle', 'XPSubject', 'comment', 'Comment', 'Description', 'description', 'COMM', 'ICMT', 'desc', '©cmt', 'tag', 'bext', 'irb']);
const maker = (kind) => (kind === 'image' ? IMG_MAKERS : kind === 'video' ? VID_MAKERS.concat(IMG_MAKERS) : AUD_MAKERS);
const asText = (bufs) => bufs.map((x) => clean(x.toString('latin1', 0, Math.min(x.length, 300000)))).join('\n');

/** Periksa kumpulan keterangan teks; kembalikan daftar bukti. */
function scanFields(fields, kind, hits) {
  for (const f of fields) {
    const v = f.value || '';
    if (!v || v.length < 3) continue;
    const soft = SOFT_KEYS.has(f.key);
    if (kind === 'image') {
      for (const [re, why] of PARAM_PATTERNS) if (re.test(v)) { hits.push({ layer: 'params', kind: 'made', hard: true, why: `${why} di ${f.src}:${f.key}` }); return; }
    }
    const m = firstHit(v, maker(kind));
    if (m) { hits.push({ layer: 'tag', kind: 'made', hard: !soft, why: `"${m}" di ${f.src}:${f.key}` }); continue; }
    const e = firstHit(v, EDIT_CLAIMS);
    if (e) { hits.push({ layer: 'tag', kind: 'edited', hard: !soft, why: `"${e}" di ${f.src}:${f.key}` }); continue; }
    const c = firstHit(v, AI_CLAIMS);
    if (c) hits.push({ layer: 'tag', kind: 'made', hard: !soft, why: `"${c}" di ${f.src}:${f.key}` });
  }
}

function scanXmp(xmps, hits, kind = 'image') {
  for (const x of xmps) {
    if (kind === 'image') for (const [re, why] of PARAM_PATTERNS) if (re.test(x)) { hits.push({ layer: 'params', kind: 'made', hard: true, why: `${why} di XMP` }); break; }
    const st = sourceTypes(x), k = kindOfSource(st);
    if (k) hits.push({ layer: 'iptc-xmp', kind: k, hard: true, why: `DigitalSourceType=${st.find((s) => /algorithmic/.test(s)) || st[0]} di XMP` });
    const ai = /AISystemUsed|AISystemVersionUsed|AIPromptInformation|AIPromptWriterName/.exec(x);
    if (ai && /<[^>]*(AISystemUsed|AIPromptInformation)[^>]*>[^<]+|(AISystemUsed|AIPromptInformation)\s*=\s*"[^"]+"/.test(x)) hits.push({ layer: 'iptc-xmp', kind: 'made', hard: true, why: `${ai[0]} di XMP` });
    const t = /(?:CreatorTool|creatortool)[^>]*>\s*([^<]+)</.exec(x) || /CreatorTool="([^"]+)"/.exec(x);
    if (t && firstHit(t[1], IMG_MAKERS.concat(AUD_MAKERS))) hits.push({ layer: 'iptc-xmp', kind: 'made', hard: true, why: `CreatorTool "${t[1].slice(0, 40)}"` });
  }
}

function scanJumbf(jumbf, kind, hits) {
  if (!jumbf.length) return false;
  const txt = asText(jumbf), st = sourceTypes(txt), k = kindOfSource(st);
  if (k) hits.push({ layer: 'c2pa', kind: k, hard: true, why: `Content Credentials: ${st.find((s) => /algorithmic/.test(s))}` });
  else {
    const m = firstHit(txt, maker(kind).concat(AI_CLAIMS, kind === 'image' ? C2PA_EXTRA_IMG : []));
    if (m) hits.push({ layer: 'c2pa', kind: 'made', hard: true, why: `Content Credentials menyebut "${m}"` });
  }
  return true;
}

function finish(type, hits, notes, ran, t0, extra = {}) {
  const hard = hits.filter((h) => h.hard), soft = hits.filter((h) => !h.hard);
  const camera = !!extra.camera;
  // Jejak kamera utuh + hanya kata bebas di keterangan (mis. teks takarir) = bukan bukti.
  const use = hard.length ? hits : (soft.length && !camera ? soft : []);
  if (!hard.length && soft.length && camera) notes.push('kata AI di keterangan foto yang punya jejak kamera utuh: diabaikan');
  const kind = use.some((h) => h.kind === 'made') ? 'made' : use.length ? 'edited' : '';
  return { v: 2, type, ai: use.length > 0, kind, hits: use.slice(0, 6).map((h) => ({ layer: h.layer, kind: h.kind, why: h.why })), notes: notes.slice(0, 8), ran, ms: Date.now() - t0, ...extra.out };
}

/** Periksa foto. Mengembalikan { ai, kind: 'made'|'edited'|'', hits, notes, ran }. Tidak pernah melempar galat. */
export function deksImage(buf, side) {
  const t0 = Date.now(), hits = [], notes = [], ran = [];
  const parts = [buf].concat(side ? [side] : []);
  let camera = false, size = '';
  try {
    for (const [pi, part] of parts.entries()) {
      const r = parseImage(part);
      if (!r.format) { if (pi === 0) notes.push('format foto tidak dikenal'); continue; }
      if (pi === 0) size = `${r.format} ${r.width}x${r.height}`;
      ran.push('c2pa', 'iptc-xmp', 'tag', 'params');
      scanJumbf(r.jumbf, 'image', hits);
      scanXmp(r.xmp, hits);
      scanFields(r.fields, 'image', hits);
      if (cameraEvidence(r)) camera = true;
      if (r.format === 'png' && r.sawIdat && !hits.some((h) => h.hard) && part.length < 6e6) {
        const px = decodePixels(part, 'png', r.width, r.height);
        if (px) {
          ran.push('stego', 'sd-watermark');
          const s = stealthInfo(px);
          if (s) hits.push({ layer: 'stego', kind: 'made', hard: true, why: `info generator tersembunyi di piksel (${s.signature})` });
          else { const w = sdWatermark(px); if (w) hits.push({ layer: 'sd-watermark', kind: 'made', hard: true, why: `watermark ${w.name} (${w.ok}/${w.of} bit)` }); }
        } else notes.push('piksel PNG tidak bisa dibaca atau terlalu besar');
      }
    }
    if (camera) notes.push('jejak kamera utuh');
  } catch (e) { notes.push('galat pemeriksaan: ' + String(e.message || e).slice(0, 60)); }
  const out = finish('image', hits, notes, [...new Set(ran)], t0, { camera, out: { size } });
  return out;
}

/** Periksa audio. */
export function deksAudio(buf) {
  const t0 = Date.now(), hits = [], notes = [], ran = [];
  try {
    const r = parseAudio(buf);
    if (!r.format) notes.push('format audio tidak dikenal');
    else {
      ran.push('c2pa', 'iptc-xmp', 'tag');
      scanJumbf(r.jumbf, 'audio', hits);
      scanXmp(r.xmp, hits, 'audio');
      scanFields(r.fields, 'audio', hits);
      notes.push(`${r.format}${r.codec ? '/' + r.codec : ''}${r.rate ? ' ' + r.rate + ' Hz' : ''}`);
    }
  } catch (e) { notes.push('galat pemeriksaan: ' + String(e.message || e).slice(0, 60)); }
  return finish('audio', hits, notes, [...new Set(ran)], t0);
}

/** Periksa video (MP4/MOV/WebM): tag berkas, XMP, Content Credentials. `side` = kotak MP4 asli tanpa mdat yang dikirim klien
 *  (video dikompres ulang di perangkat sehingga metadata aslinya hilang di berkas yang diunggah). */
export function deksVideo(buf, side) {
  const t0 = Date.now(), hits = [], notes = [], ran = [];
  try {
    for (const [pi, part] of [buf].concat(side ? [side] : []).entries()) {
      const r = parseAudio(part);
      if (!r.format) { if (pi === 0) notes.push('format video tidak dikenal'); continue; }
      ran.push('c2pa', 'iptc-xmp', 'tag');
      scanJumbf(r.jumbf, 'video', hits);
      scanXmp(r.xmp, hits, 'video');
      scanFields(r.fields, 'video', hits);
      if (pi === 0) notes.push(`${r.format}${r.codec ? '/' + r.codec : ''}`);
      else notes.push('metadata berkas asli diperiksa');
    }
  } catch (e) { notes.push('galat pemeriksaan: ' + String(e.message || e).slice(0, 60)); }
  return finish('video', hits, notes, [...new Set(ran)], t0);
}

/** Ringkasan untuk disimpan (kolom deks) dan log: tanpa teks panjang. */
export const brief = (rep) => JSON.stringify({ v: rep.v, t: rep.type, ai: rep.ai, k: rep.kind, h: rep.hits, n: rep.notes, r: rep.ran });
